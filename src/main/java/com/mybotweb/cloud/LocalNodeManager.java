package com.mybotweb.cloud;

/**
 * 【留空待实现】本地算力节点管理器 —— 维护"本地节点在不在线"。
 *
 * <p>这是整个云端/本地切换机制的<b>状态中心</b>：路由策略要知道
 * "本地现在能不能用"，靠的就是本类。
 *
 * <p><b>为什么定义成接口而不直接写类？</b>
 * 因为实现方式会变：现在是本地程序直连腾讯（根本没有"节点"这个概念），
 * 将来本地程序作为一个节点连到云端，判断在线的方式是"心跳时间戳是否新鲜"。
 * 先定接口，等有云端时再写实现。
 *
 * <p>═══════════════════════════════════════════════════════════
 * <p><b>实现时要考虑的四件事</b>
 *
 * <p><b>1. 在线状态的判定标准</b>
 * 不能是"曾经连上过"，必须是"最近还在心跳"。典型做法：
 * 本地节点每 15 秒发一次心跳，超过 45 秒没收到就判定离线。
 * 阈值的取法是"心跳间隔的 3 倍"——留出两次丢包的容忍空间，
 * 避免网络抖动被误判成离线（误判离线会导致消息被甩去云端，多花钱）。
 *
 * <p><b>2. 状态变更时的通知</b>
 * 本地节点掉线这件事，管理员应该能知道。做法是提供一个监听回调，
 * 由它去给管理员发一条 QQ 消息。注意<b>不能每秒都发</b>——
 * 网络抖动会导致"离线了/上线了"反复横跳，必须做抖动抑制
 * （比如状态稳定持续 30 秒才通知）。
 *
 * <p><b>3. 支持多个本地节点吗？</b>
 * 建议<b>不支持</b>，至少一开始不要。规格里本地节点是"可选算力节点"，
 * 语义上只有一个。支持多节点会立刻带来"派给哪个节点""某个节点卡住怎么办"
 * 一堆问题，而收益接近零。如果哪天真需要，再把它改成
 * {@code Map<nodeId, NodeStatus>} 并把本接口的方法加一个 nodeId 参数。
 *
 * <p><b>4. 状态存哪？</b>
 * 单实例部署（一台云服务器）时放内存就够。将来多实例部署要注意：
 * 状态必须放 Redis，否则"消息落在实例 A、本地节点连的是实例 B"
 * 会导致 A 认为本地离线——这是最难查的一类 bug。
 *
 * <p>═══════════════════════════════════════════════════════════
 * <p>实现类：{@code InMemoryLocalNodeManager}（{@code @Component}），
 * 被 {@code ModelRouterImpl} 和 {@code /status} 命令注入使用。
 * （这段注释以前写的是"没有任何实现类"，那已经不对了。）
 *
 * <p><b>它只是"本地算力可用"的两个来源之一</b> —— 另一个是本机模型服务的
 * 直接探测。两者是"或"的关系，见 {@code ModelRouterImpl.isLocalAvailable()}。
 *
 * @author mybotweb
 */
public interface LocalNodeManager {

    /**
     * 【待实现】判断本地节点当前是否可用。
     *
     * <p>会被每条消息调用一次，实现必须廉价（读内存字段，不做 IO）。
     *
     * @return 在线且心跳新鲜返回 {@code true}
     */
    boolean isOnline();

    /**
     * 【待实现】记录一次心跳。
     *
     * <p>由 {@code LocalNodeEndpoint} 在收到心跳消息时调用。
     *
     * @param nodeId 节点标识（本地机器的名字，便于排查是哪台）
     */
    void onHeartbeat(String nodeId);

    /**
     * 【待实现】记录节点断开。
     *
     * <p>注意区分"主动断开"和"异常断开"：主动断开（管理员要关机）
     * 可以直接标记离线；异常断开建议等待心跳超时再判定，
     * 因为短时间的网络重连不该触发状态切换。
     *
     * @param nodeId  节点标识
     * @param graceful 是否主动断开
     */
    void onDisconnect(String nodeId, boolean graceful);

    /**
     * 【待实现】取最后一次心跳距今的毫秒数，用于 {@code /status} 展示。
     *
     * <p>返回值要能区分"从未连过"和"很久没心跳"两种情况，
     * 例如从未连过时返回 {@code -1}。
     *
     * @return 毫秒数；从未连过返回 {@code -1}
     */
    long millisSinceLastHeartbeat();

    /**
     * 【待实现】取最后一次心跳的时间戳，供日志和监控使用。
     *
     * @return 时间戳（毫秒）；从未连过返回 {@code 0}
     */
    long lastHeartbeatAt();
}
